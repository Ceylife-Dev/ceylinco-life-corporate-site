import type { Metadata, Viewport } from "next";
import { Noto_Sans_Sinhala, Noto_Sans_Tamil, Plus_Jakarta_Sans } from "next/font/google";
import { Suspense } from "react";
import { Header } from "@/components/header/Header";
import { HeaderFallback } from "@/components/header/HeaderFallback";
import { BottomNav, BottomNavFallback } from "@/components/site/BottomNav";
import { ChatButton } from "@/components/site/ChatButton";
import { Footer } from "@/components/site/Footer";
import { InstallPrompt } from "@/components/site/InstallPrompt";
import { PwaRegister } from "@/components/site/PwaRegister";
import { pwa } from "@/content/pwa";
import { colourToken } from "@/lib/tokens";
import { site } from "@/content/site";
import "./globals.css";

/* next/font options must be written as literals (it reads them at build time).
   Fonts are downloaded at build time and served from our own domain (no calls
   to Google from the visitor's browser). `variable` exposes each font as a CSS
   variable that src/styles/tokens.css folds into the --font-sans stack. */
const jakarta = Plus_Jakarta_Sans({
  subsets: ["latin", "latin-ext"],
  weight: ["400", "500", "600", "700"], // the only weights the design uses
  display: "swap",
  variable: "--nf-jakarta",
});

// Plus Jakarta Sans has no Sinhala or Tamil letters, so these two cover them.
// `preload: false` => only downloaded when a page actually shows that script.
const notoSinhala = Noto_Sans_Sinhala({
  subsets: ["sinhala"],
  weight: ["400", "500", "600", "700"], // the only weights the design uses
  display: "swap",
  preload: false,
  variable: "--nf-noto-sinhala",
});

const notoTamil = Noto_Sans_Tamil({
  subsets: ["tamil"],
  weight: ["400", "500", "600", "700"], // the only weights the design uses
  display: "swap",
  preload: false,
  variable: "--nf-noto-tamil",
});

export const metadata: Metadata = {
  title: { default: site.name, template: `%s | ${site.name}` },
  description: site.description,
  applicationName: pwa.app.name,
  // The installed app: the manifest is generated by src/app/manifest.ts. These tags are for iPhone and iPad.
  appleWebApp: { capable: true, title: pwa.app.shortName, statusBarStyle: "default" },
  icons: { icon: "/icons/icon-192.png", apple: "/icons/apple-touch-icon.png" },
  formatDetection: { telephone: false },
};

// viewport-fit=cover lets the installed app use the whole screen; the safe-area utilities in globals.css keep content clear
// of the notch and the home indicator. theme-color is the `brand` token, read from tokens.css (also used in the manifest).
export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  viewportFit: "cover",
  themeColor: colourToken("brand"),
};

/*
 * Runs before the first paint: if the text case review tool is on (development, or ?review=1 for this visit; never in the installed app)
 * and title case was chosen last time, mark <html> so the flagged text stays hidden until CaseToggle has applied it (no flash).
 * Everything is in try / catch. It does nothing for normal visitors.
 */
const caseModeScript = `try{var d=${process.env.NODE_ENV !== "production"},q=new URLSearchParams(location.search);if(q.get("review")==="1")sessionStorage.setItem("cl:review","1");if((d||sessionStorage.getItem("cl:review")==="1")&&!matchMedia("(display-mode: standalone)").matches&&localStorage.getItem("cl:case")==="title")document.documentElement.setAttribute("data-case-mode","title")}catch(e){}`;

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    // suppressHydrationWarning is only for the attributes of this <html> tag: browser extensions and the page language
    // switch (see Header) can add or change attributes (lang, style) before React hydrates. It does not hide warnings inside the page.
    <html
      lang="en"
      className={`${jakarta.variable} ${notoSinhala.variable} ${notoTamil.variable}`}
      suppressHydrationWarning
    >
      <head>
        <script dangerouslySetInnerHTML={{ __html: caseModeScript }} />
      </head>
      <body className="min-h-dvh antialiased">
        {/* The header reads the current address (to mark the current page), so Next.js needs a Suspense
            boundary around it for pages with dynamic addresses. */}
        <Suspense fallback={<HeaderFallback />}>
          <Header />
        </Suspense>
        {children}
        <Footer />
        <ChatButton />
        <InstallPrompt />
        {/* The bottom bar reads the URL, so it sits inside Suspense like the header. */}
        <Suspense fallback={<BottomNavFallback />}>
          <BottomNav />
        </Suspense>
        <PwaRegister />
      </body>
    </html>
  );
}
